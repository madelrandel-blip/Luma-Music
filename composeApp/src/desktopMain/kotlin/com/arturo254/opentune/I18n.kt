import java.util.Locale

fun tr(key: String, vararg args: Any?): String = I18n.tr(key, *args)

/**
 * Simple UI translation helper.
 *
 * Every user-facing string is written in Spanish and passed through [tr].
 * For "es" the source is returned as-is; for "en"/"pt" it is translated.
 * The active language comes from [DesktopPreferences.contentLanguage]
 * (reactive, so calling [tr] during composition updates the UI).
 */
object I18n {
    private val supported = setOf("es", "en", "pt")

    fun current(): String {
        val stored = DesktopPreferences.contentLanguage
        if (stored in supported) return stored
        return when (Locale.getDefault().language.lowercase()) {
            "es" -> "es"
            "pt" -> "pt"
            else -> "en"
        }
    }

    fun tr(key: String, vararg args: Any?): String {
        val lang = current()
        val text = when (lang) {
            "en" -> EN[key]
            "pt" -> PT[key]
            else -> null
        } ?: key
        if (args.isEmpty()) return text
        return Regex("\\{(\\d+)}").replace(text) { m ->
            val idx = m.groupValues[1].toIntOrNull() ?: return@replace m.value
            args.getOrNull(idx)?.toString() ?: m.value
        }
    }

